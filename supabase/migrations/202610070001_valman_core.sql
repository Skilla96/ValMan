-- Profiles: all enabled ValMan users can see colleague name/role; only admins modify them.
drop policy if exists profiles_read on public.profiles;
create policy profiles_read on public.profiles for select to authenticated
using (public.valman_is_enabled());

drop policy if exists profiles_admin_write on public.profiles;
create policy profiles_admin_write on public.profiles for all to authenticated
using (public.valman_is_admin())
with check (public.valman_is_admin());

-- Invites are administrative only. Claiming happens through the Edge Function.
drop policy if exists invites_admin on public.employee_invites;
create policy invites_admin on public.employee_invites for all to authenticated
using (public.valman_is_admin())
with check (public.valman_is_admin());

-- Shared workspace. App-level roles can be tightened later without changing the data format.
drop policy if exists records_read on public.records;
create policy records_read on public.records for select to authenticated
using (public.valman_is_enabled());

drop policy if exists records_insert on public.records;
create policy records_insert on public.records for insert to authenticated
with check (public.valman_is_enabled() and updated_by = auth.uid());

drop policy if exists records_update on public.records;
create policy records_update on public.records for update to authenticated
using (public.valman_is_enabled())
with check (public.valman_is_enabled() and updated_by = auth.uid());

drop policy if exists records_delete on public.records;
create policy records_delete on public.records for delete to authenticated
using (public.valman_is_enabled());

