create extension if not exists pgcrypto;

create table if not exists public.profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  employee_id text not null unique,
  name text not null,
  role text not null check (role in ('ADMIN','MECCANICO','ELETTRICO','LETTURA')),
  enabled boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.employee_invites (
  employee_id text primary key,
  name text not null,
  role text not null check (role in ('MECCANICO','ELETTRICO','LETTURA')),
  enabled boolean not null default true,
  activation_hash text not null,
  claimed_by uuid references auth.users(id) on delete set null,
  claimed_at timestamptz,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.records (
  collection text not null check (collection in (
    'machines','faults','interventions','leaves','communications','handovers',
    'documents','shifts','turnationImages','turnationOcr'
  )),
  record_key text not null,
  data jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now(),
  updated_by uuid references auth.users(id) on delete set null,
  primary key (collection, record_key)
);

create index if not exists idx_records_collection on public.records(collection);
create index if not exists idx_records_updated_at on public.records(updated_at);
create index if not exists idx_records_data_gin on public.records using gin(data);

create table if not exists public.attachments (
  id uuid primary key default gen_random_uuid(),
  title text not null,
  original_name text not null,
  mime text,
  machine text,
  storage_path text not null unique,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  openai_file_id text
);

create table if not exists public.audit_log (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete set null,
  action text not null,
  entity text,
  entity_id text,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create or replace function public.valman_touch_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists trg_profiles_updated_at on public.profiles;
create trigger trg_profiles_updated_at before update on public.profiles
for each row execute function public.valman_touch_updated_at();

drop trigger if exists trg_employee_invites_updated_at on public.employee_invites;
create trigger trg_employee_invites_updated_at before update on public.employee_invites
for each row execute function public.valman_touch_updated_at();

create or replace function public.valman_is_enabled()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists(
    select 1 from public.profiles p
    where p.user_id = auth.uid() and p.enabled = true
  );
$$;

create or replace function public.valman_is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists(
    select 1 from public.profiles p
    where p.user_id = auth.uid() and p.enabled = true and p.role = 'ADMIN'
  );
$$;

grant execute on function public.valman_is_enabled() to authenticated;
grant execute on function public.valman_is_admin() to authenticated;

-- Admin creates an employee ID and receives a one-time activation code.
create or replace function public.admin_create_employee(
  p_employee_id text,
  p_name text,
  p_role text
)
returns table(employee_id text, activation_code text)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_id text;
  v_code text;
  v_role text;
begin
  if not public.valman_is_admin() then
    raise exception 'ADMIN_REQUIRED';
  end if;

  v_id := upper(regexp_replace(trim(coalesce(p_employee_id,'')), '[^A-Z0-9_.-]', '', 'g'));
  if length(v_id) < 2 then raise exception 'INVALID_EMPLOYEE_ID'; end if;
  if trim(coalesce(p_name,'')) = '' then raise exception 'NAME_REQUIRED'; end if;

  v_role := upper(coalesce(p_role,'LETTURA'));
  if v_role not in ('MECCANICO','ELETTRICO','LETTURA') then v_role := 'LETTURA'; end if;

  v_code := upper(substr(encode(gen_random_bytes(8),'hex'), 1, 10));

  insert into public.employee_invites(
    employee_id,name,role,enabled,activation_hash,created_by
  ) values (
    v_id,trim(p_name),v_role,true,encode(digest(v_code,'sha256'),'hex'),auth.uid()
  )
  on conflict (employee_id) do update set
    name = excluded.name,
    role = excluded.role,
    enabled = true,
    activation_hash = excluded.activation_hash,
    claimed_by = null,
    claimed_at = null,
    created_by = auth.uid(),
    updated_at = now();

  insert into public.audit_log(user_id,action,entity,entity_id,details)
  values(auth.uid(),'CREATE_EMPLOYEE_INVITE','employee',v_id,jsonb_build_object('role',v_role));

  return query select v_id, v_code;
end;
$$;

grant execute on function public.admin_create_employee(text,text,text) to authenticated;

